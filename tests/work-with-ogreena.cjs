const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
const home=read('index.html');
const careers=read('hiring-application/index.html');
const account=read('careers-account/index.html');
const script=read('careers-account/careers-account.js');
const migration=read('supabase/migrations/20261117190000_work_with_ogreena_applications.sql');
const detailsStart=home.indexOf('<h3>Profile details</h3>');
const detailsEnd=home.indexOf('</section>',detailsStart);
const work=home.indexOf('Work With Ogreena');
assert.ok(detailsStart>=0&&work>detailsStart&&work<detailsEnd,'Work With Ogreena must remain inside Profile Details');
assert.match(home,/Offer Your Services/);
assert.match(home,/View Available Jobs/);
assert.match(careers,/HVAC Installer Needed — Heat Pump &amp; 3 Mini-Split Installation \(Labor Only\)/);
assert.match(account,/careerServiceChoices/);
assert.match(script,/getAll\('service_categories'\)/);
assert.match(script,/getAll\('specialties'\)/);
assert.match(script,/hvac-installation/);
assert.match(migration,/owner-reviewed/);
assert.match(migration,/electrical-services/);
assert.match(migration,/hauling/);
assert.match(migration,/drop function if exists public\.submit_job_application\(text,text,text,text,text\)/);
assert.doesNotMatch(migration,/mattress-cleaning|floor-polishing/);
console.log('Work With Ogreena placement, categories, job listing and private application controls: PASS');
